"""Generate synthetic CHI-format fixtures without reading experimental data."""
from __future__ import annotations

import argparse
import math
from pathlib import Path

SAMPLES = (
    ("O-0.1MNa-5mv-900.txt", -.8, 900, False, False),
    ("O-0.1MNa-5mv-1225.txt", -.8, 1225, False, False),
    ("Ar-5mv-beijing.txt", -1.15, None, False, True),
    ("盘环-o-CS-第二个电极.txt", -.9, None, True, False),
)


def generate(output):
    output = Path(output)
    targets = [output / sample[0] for sample in SAMPLES]
    if any(path.exists() for path in targets):
        raise FileExistsError("目标中已有示例文件；请使用一个新的空目录，避免覆盖实验数据。")
    output.mkdir(parents=True, exist_ok=True)
    for name, low, rpm, rrde, background in SAMPLES:
        high, step = .1, .001
        count = round((high-low)/step)
        headers = ["SYNTHETIC DEMO - NOT EXPERIMENTAL DATA", "Cyclic Voltammetry",
            f"File: synthetic/{name}", "Instrument Model: CHI760F (format simulation)",
            "Note: Generated by tools/generate_demo_data.py; no measured currents used.", "",
            f"Init E (V) = {low}", f"High E (V) = {high}", f"Low E (V) = {low}",
            "Init P/N = P", "Scan Rate (V/s) = 0.005", "Segment = 4",
            "Sample Interval (V) = 0.001", "Quiet Time (sec) = 6", "Sensitivity (A/V) = 0.001",
            "Comp R (ohm) = 0", "UC R (ohm) = 0"]
        if rrde:
            headers.extend(["2nd E (V) = 0.2", "Sens 2 (A/V) = 0.0001"])
        headers.extend(["", "Potential/V, i1/A, i2/A" if rrde else "Potential/V, Current/A"])
        lines = []
        for index in range(4*count):
            position = index % (2*count)
            ascending = position < count
            potential = low + position*step if ascending else high - (position-count)*step
            baseline = -2e-6 + 2e-6*potential + (5e-7 if ascending else -5e-7)
            reaction = 1 / (1 + math.exp((potential+.25)/.08))
            disk = baseline if background else baseline - (1e-5 if rrde else 4e-4*math.sqrt(rpm/900))*reaction
            values = [f"{potential:.3f}", f"{disk:.12e}"]
            if rrde:
                values.append(f"{5e-7*reaction + 1e-8:.12e}")
            lines.append(", ".join(values))
        (output/name).write_text("\n".join(headers+lines)+"\n", encoding="utf-8")
    (output/"README.md").write_text(
        "# 合成演示数据\n\n这四份文件由 `tools/generate_demo_data.py` 生成，没有使用实测电流。"
        "文件名保留历史测试命名以兼容回归测试，其中的电解液字样不表示已测 pH。"
        "数据仅用于导入、扫描选择、背景、绘图和界面测试，不能作为催化剂性能或选择性证据。\n",
        encoding="utf-8")
    return targets


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="A new/empty target directory")
    args = parser.parse_args()
    for path in generate(args.output):
        print(path.name)
